// Marketing link + QR generator and verifier.
//
// Reads src/config/marketing-links.ts (single source of truth) and produces:
//   docs/marketing/UTM-MASTER-LINKS.md
//   docs/marketing/UTM-MASTER-LINKS.csv
//   docs/marketing/WHERE-TO-PASTE-UTM-LINKS.md
//   public/marketing/qr/<name>.svg | <name>.png | <name>-print.png
//
// Every QR is generated from the registry and INDEPENDENTLY decode-verified
// (PNG via jsQR; SVG rasterized with sharp then decoded) against the exact
// intended URL. A mismatch fails the run.
//
// Usage:
//   node scripts/generate-marketing-links.mjs          generate docs + QRs, verify
//   node scripts/generate-marketing-links.mjs --qr     force-regenerate every QR
//   node scripts/generate-marketing-links.mjs --check  verify only (no writes)

import fs from 'node:fs';
import path from 'node:path';
import QRCode from 'qrcode';
import jsQR from 'jsqr';
import pngjs from 'pngjs';
import sharp from 'sharp';
import {
  marketingLinks,
  qrAssets,
  destinations,
  resolveSiteUrl,
  linkUrl,
} from '../src/config/marketing-links.ts';

const { PNG } = pngjs;

const args = new Set(process.argv.slice(2));
const CHECK_ONLY = args.has('--check');
const FORCE_QR = args.has('--qr');

const SITE_URL = resolveSiteUrl(process.env.PUBLIC_SITE_URL);
const SITE_PENDING = SITE_URL.includes('pending-website-url.invalid');

const DOC_DIR = path.join('docs', 'marketing');
const QR_DIR = path.join('public', 'marketing', 'qr');
const MASTER_MD = path.join(DOC_DIR, 'UTM-MASTER-LINKS.md');
const MASTER_CSV = path.join(DOC_DIR, 'UTM-MASTER-LINKS.csv');
const CHEAT_MD = path.join(DOC_DIR, 'WHERE-TO-PASTE-UTM-LINKS.md');

const QR_STYLE = { errorCorrectionLevel: 'H', margin: 4, color: { dark: '#3d3036', light: '#ffffff' } };
const UTM_VALUE = /^[a-z0-9_]+$/;
const FORBIDDEN_MEDIA = new Set(['cpc', 'ppc', 'paid_search', 'display', 'cpm']);
const FORBIDDEN_SOURCES = new Set(['googleads', 'adwords']);

// ── Registry validation ──────────────────────────────────────────────────────
const problems = [];
const ids = new Map();
const tuples = new Map();
const byId = new Map(marketingLinks.map((link) => [link.id, link]));

for (const link of marketingLinks) {
  if (!UTM_VALUE.test(link.id)) problems.push(`id "${link.id}" must be lowercase snake_case`);
  if (ids.has(link.id)) problems.push(`duplicate link id "${link.id}"`);
  ids.set(link.id, true);

  for (const [key, value] of Object.entries(link.utm)) {
    if (!value) continue;
    if (!UTM_VALUE.test(value)) {
      problems.push(`${link.id}: utm_${key} "${value}" must be lowercase snake_case (no spaces/uppercase)`);
    }
    if (value.includes('@') || /\d{7,}/.test(value)) {
      problems.push(`${link.id}: utm_${key} "${value}" looks like PII (email/phone digits forbidden)`);
    }
  }
  if (!Object.values(destinations).includes(link.path)) {
    problems.push(`${link.id}: destination "${link.path}" is not a known internal page`);
  }
  if (FORBIDDEN_MEDIA.has(link.utm.medium) || FORBIDDEN_SOURCES.has(link.utm.source)) {
    problems.push(
      `${link.id}: manual Google Ads UTMs are prohibited — Google Ads must use auto-tagging (gclid/gbraid/wbraid/gad_*)`,
    );
  }
  const tuple = [link.utm.source, link.utm.medium, link.utm.campaign, link.utm.content ?? '', link.path].join('|');
  if (tuples.has(tuple)) {
    problems.push(`duplicate campaign definition: "${tuples.get(tuple)}" and "${link.id}" both use ${tuple}`);
  }
  tuples.set(tuple, link.id);
}

for (const asset of qrAssets) {
  if (!/^[a-z0-9-]+$/.test(asset.id)) problems.push(`QR id "${asset.id}" must be lowercase`);
  if (!byId.has(asset.linkId)) problems.push(`QR "${asset.id}" references unknown link "${asset.linkId}"`);
}
if (new Set(qrAssets.map((a) => a.id)).size !== qrAssets.length) problems.push('duplicate QR asset ids');

if (problems.length) {
  console.error('REGISTRY VALIDATION FAILED:');
  for (const problem of problems) console.error(` - ${problem}`);
  process.exit(1);
}

// ── Document generation ──────────────────────────────────────────────────────
const baseLinks = marketingLinks.filter((link) => link.manual && link.path === destinations.home && !link.pending);
const pendingLinks = marketingLinks.filter((link) => link.pending);
const campaignLinks = marketingLinks.filter((link) => !baseLinks.includes(link) && !link.pending);

const pendingNote = SITE_PENDING
  ? '\n> **WARNING — the production domain is PENDING.** Every URL below uses a placeholder\n> origin. Regenerate this document (`npm run marketing:links`) with PUBLIC_SITE_URL set\n> after the domain is approved before anything is printed. Print QRs are not usable yet.\n'
  : '';

const masterMd = `# UTM & campaign link master registry

**Generated by \`scripts/generate-marketing-links.mjs\` — do not edit by hand.**
Source of truth: \`src/config/marketing-links.ts\`. Site: ${SITE_URL}.
${pendingNote}
## Rules (non-negotiable)

- UTMs are for **inbound marketing links only**. Never add them to internal navigation,
  canonical URLs, sitemap entries, \`tel:\`/\`sms:\`/\`mailto:\` links, or review links.
- The site never forces UTMs to persist while visitors browse — attribution is captured
  once on landing and attached to lead records.
- Lowercase \`snake_case\` values only. Never include names, phone numbers, emails,
  addresses, ZIP codes or any other personal information.
- **Google Ads:** no manual UTMs. Use Google auto-tagging (gclid / gbraid / wbraid /
  gad_*) — the site preserves those parameters untouched.
- \`utm_term\` is not used (no paid-keyword campaigns).

## Base channel links (${baseLinks.length})

| Channel | Placement | Final URL | Purpose |
| --- | --- | --- | --- |
${baseLinks.map((link) => `| ${link.channel} | ${link.placement} | ${linkUrl(link, SITE_URL)} | ${link.purpose} |`).join('\n')}

## Pending — prepared, do NOT publish yet (${pendingLinks.length})

These URLs are prepared for when the public profiles exist. Do **not** paste them anywhere yet.

| Channel | Placement | Prepared URL (not active) | Why pending |
| --- | --- | --- | --- |
${pendingLinks.map((link) => `| ${link.channel} | ${link.placement} | ${linkUrl(link, SITE_URL)} | ${link.purpose} |`).join('\n')}

## Campaign & outreach links (${campaignLinks.length})

| Channel | Placement | Final URL | Purpose |
| --- | --- | --- | --- |
${campaignLinks.map((link) => `| ${link.channel} | ${link.placement} | ${linkUrl(link, SITE_URL)} | ${link.purpose} |`).join('\n')}

## QR assets (${qrAssets.length})

| Asset | Resolves to | Placement | File |
| --- | --- | --- | --- |
${qrAssets
  .map((asset) => {
    const link = byId.get(asset.linkId);
    return `| ${asset.purpose} | ${link ? linkUrl(link, SITE_URL) : 'MISSING'} | ${asset.placement} | \`public/marketing/qr/${asset.id}.svg\`${asset.pending ? ' (pending)' : ''} |`;
  })
  .join('\n')}
`;

const csvRows = [
  ['id', 'channel', 'campaign', 'placement', 'final_url', 'purpose', 'status', 'where_owner_pastes'],
  ...marketingLinks.map((link) => [
    link.id,
    link.channel,
    link.campaign,
    link.placement,
    linkUrl(link, SITE_URL),
    link.purpose,
    link.pending ? 'PENDING' : 'ACTIVE',
    link.whereToPaste,
  ]),
];
const csvEscape = (value) => `"${String(value).replaceAll('"', '""')}"`;
const masterCsv = csvRows.map((row) => row.map(csvEscape).join(',')).join('\n') + '\n';

const ready = marketingLinks.filter((link) => link.manual && !link.pending);
const notReady = marketingLinks.filter((link) => link.pending);

const cheatMd = `# Where to paste each tracked link

**Generated by \`scripts/generate-marketing-links.mjs\` — do not edit by hand.**
${pendingNote}
## Ready to use (${ready.length})

${ready
  .map(
    (link) =>
      `### ${link.channel} — ${link.placement}\n\n- Paste where: ${link.whereToPaste}\n- Link: ${linkUrl(link, SITE_URL)}\n- Purpose: ${link.purpose}\n`,
  )
  .join('\n')}

## Not yet — waiting on profiles or final domain (${notReady.length})

${notReady
  .map(
    (link) =>
      `### ${link.channel} — ${link.placement}\n\n- Do NOT paste yet: ${link.purpose}\n- Prepared link: ${linkUrl(link, SITE_URL)}\n`,
  )
  .join('\n')}
`;

// ── QR generation + independent verification ─────────────────────────────────
async function verifyPng(buffer, expectedUrl, label) {
  const png = PNG.sync.read(buffer);
  const code = jsQR(new Uint8ClampedArray(png.data), png.width, png.height);
  if (!code || code.data !== expectedUrl) {
    throw new Error(`QR decode mismatch for ${label}: got "${code?.data ?? 'nothing'}"`);
  }
}

async function verifySvg(svg, expectedUrl, label) {
  const png = await sharp(Buffer.from(svg)).png().toBuffer();
  await verifyPng(png, expectedUrl, `${label} (svg raster)`);
}

async function generateQrAssets() {
  fs.mkdirSync(QR_DIR, { recursive: true });
  let written = 0;
  for (const asset of qrAssets) {
    const link = byId.get(asset.linkId);
    if (!link) throw new Error(`QR ${asset.id} references unknown link ${asset.linkId}`);
    const url = linkUrl(link, SITE_URL);

    const svgPath = path.join(QR_DIR, `${asset.id}.svg`);
    const pngPath = path.join(QR_DIR, `${asset.id}.png`);
    const printPath = path.join(QR_DIR, `${asset.id}-print.png`);

    const svg = await QRCode.toString(url, { type: 'svg', ...QR_STYLE });
    const png = await QRCode.toBuffer(url, { type: 'png', width: 1024, ...QR_STYLE });
    const printPng = await QRCode.toBuffer(url, {
      type: 'png',
      width: 2048,
      errorCorrectionLevel: 'H',
      margin: 6,
      color: { dark: '#000000', light: '#ffffff' },
    });

    if (CHECK_ONLY && !FORCE_QR) {
      for (const file of [svgPath, pngPath, printPath]) {
        if (!fs.existsSync(file)) throw new Error(`Missing QR file: ${file} — run npm run marketing:qr`);
      }
      // Verify the committed PNG decodes to the intended URL.
      await verifyPng(fs.readFileSync(pngPath), url, `${asset.id}.png`);
      await verifySvg(fs.readFileSync(svgPath, 'utf8'), url, `${asset.id}.svg`);
    } else {
      fs.writeFileSync(svgPath, svg);
      fs.writeFileSync(pngPath, png);
      fs.writeFileSync(printPath, printPng);
      await verifyPng(png, url, `${asset.id}.png`);
      await verifySvg(svg, url, `${asset.id}.svg`);
      written += 3;
    }
  }
  return written;
}

function checkDocs() {
  for (const [file, content] of [
    [MASTER_MD, masterMd],
    [MASTER_CSV, masterCsv],
    [CHEAT_MD, cheatMd],
  ]) {
    if (!fs.existsSync(file)) {
      throw new Error(`Missing generated document ${file} — run npm run marketing:links`);
    }
    const existing = fs.readFileSync(file, 'utf8');
    if (existing !== content) {
      throw new Error(`${file} is out of date — run npm run marketing:links`);
    }
  }
}

try {
  if (CHECK_ONLY && !FORCE_QR) {
    checkDocs();
    await generateQrAssets();
    console.log('✓ registry valid, documents in sync, every QR decodes to its intended URL');
  } else {
    fs.mkdirSync(DOC_DIR, { recursive: true });
    fs.writeFileSync(MASTER_MD, masterMd);
    fs.writeFileSync(MASTER_CSV, masterCsv);
    fs.writeFileSync(CHEAT_MD, cheatMd);
    const written = await generateQrAssets();
    console.log(`✓ wrote 3 documents and ${written} QR files (all decode-verified)`);
    if (SITE_PENDING) {
      console.log('! production domain is PENDING — regenerate with PUBLIC_SITE_URL before printing');
    }
  }
} catch (error) {
  console.error(`marketing-links failed: ${error instanceof Error ? error.message : error}`);
  process.exit(1);
}
