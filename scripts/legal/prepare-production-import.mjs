#!/usr/bin/env node
// Build the reviewed SQL for importing the owner-approved legal library into
// production D1. This script never connects to Cloudflare. It verifies the
// approved manifest and the staging text hashes, applies the owner-approved
// packet enforcement policy, and writes a deterministic SQL file for an
// authorized `wrangler d1 execute --remote --file` run.
//
// Usage:
//   node scripts/legal/prepare-production-import.mjs \
//     --staging <STAGING-IMPORT-2026-11-22.json> \
//     --manifest <APPROVED-VERSION-MANIFEST-2026-11-22.json> \
//     --owner-admin-id <production admin_users.id> \
//     --out <legal-import.sql>

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { normalizeImport } from './packet-policy.mjs';

function args() {
  const values = {};
  const argv = process.argv.slice(2);
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index].startsWith('--') && argv[index + 1]) {
      values[argv[index].slice(2)] = argv[index + 1];
      index += 1;
    }
  }
  return values;
}

function sha256(value) {
  return crypto.createHash('sha256').update(value, 'utf8').digest('hex');
}

function sqlText(value) {
  return `'${String(value ?? '').replace(/\u0000/g, '').replace(/'/g, "''")}'`;
}

function sqlJson(value) {
  return sqlText(JSON.stringify(value));
}

function fail(message) {
  throw new Error(message);
}

const input = args();
for (const required of ['staging', 'manifest', 'owner-admin-id', 'out']) {
  if (!input[required]) fail(`missing --${required}`);
}

const staging = normalizeImport(JSON.parse(fs.readFileSync(input.staging, 'utf8')));
const manifest = JSON.parse(fs.readFileSync(input.manifest, 'utf8'));
if (manifest.approvedCount !== 27 || !Array.isArray(manifest.documents) || manifest.documents.length !== 27) {
  fail('approved manifest does not contain exactly 27 documents');
}
if (!Array.isArray(staging.documents) || staging.documents.length !== 27) {
  fail('staging import does not contain exactly 27 documents');
}
if (!Array.isArray(staging.packets) || staging.packets.length !== 10) {
  fail('staging import does not contain exactly 10 packets');
}
const archived = new Set((manifest.archives ?? []).map((entry) => String(entry.id)));
const manifestById = new Map(manifest.documents.map((doc) => [String(doc.id), doc]));
const errors = [];
const documents = staging.documents.map((doc) => {
  const approved = manifestById.get(String(doc.id));
  if (!approved) {
    errors.push(`${doc.id}: not in approved manifest`);
    return doc;
  }
  if (approved.title !== doc.title || approved.version !== doc.version) {
    errors.push(`${doc.id}: title or version differs from the approved manifest`);
  }
  if (archived.has(String(doc.id))) errors.push(`${doc.id}: archived document in import set`);
  let notes = {};
  try {
    notes = JSON.parse(String(doc.packetNotes ?? '{}'));
  } catch {
    notes = {};
  }
  if (notes.approvedDocxSha256 !== approved.docxSha256) {
    errors.push(`${doc.id}: packet note DOCX hash does not match the approved manifest`);
  }
  if (notes.approvedAt !== approved.approvedAt) {
    errors.push(`${doc.id}: packet note approval timestamp differs from the manifest`);
  }
  const actual = sha256(String(doc.contentText ?? ''));
  if (actual !== doc.contentSha256) {
    errors.push(`${doc.id}: staging text hash mismatch (expected ${doc.contentSha256}, got ${actual})`);
  }
  if (/OWNER REVIEW DRAFT|NOT EFFECTIVE UNTIL APPROVED|REVIEW[- ]ONLY|INTERNAL DRAFT|DRAFT FOR OWNER/i.test(String(doc.contentText ?? ''))) {
    errors.push(`${doc.id}: customer-facing content contains an internal review notice`);
  }
  return doc;
});
if (errors.length) fail(`approved source verification failed:\n- ${errors.join('\n- ')}`);

const lines = [
  '-- Sparkling Standard owner-approved legal library import.',
  '-- Generated by scripts/legal/prepare-production-import.mjs.',
  '-- 27 owner-approved templates, 10 packets. Residential packets active;',
  '-- facility, specialty, property-management, STR and employee packets stay',
  '-- inactive until their own acceptance run.',
  '',
];

const approvedAt = new Date().toISOString();
for (const doc of documents) {
  const packetNotes = String(doc.packetNotes ?? '');
  lines.push(
    `INSERT INTO document_templates
       (id, title, category, version, status, source_kind, content_text, content_sha256, r2_key,
        signer_party, requires_countersignature, requires_verification, approved_by_admin_user_id,
        approved_at, created_by_admin_user_id, family_key, effective_date, legal_review_status,
        supersedes_template_id, packet_notes)
     VALUES
       (${sqlText(doc.id)}, ${sqlText(doc.title)}, ${sqlText(doc.category)}, ${sqlText(doc.version)},
        'approved', 'text', ${sqlText(doc.contentText)}, ${sqlText(doc.contentSha256)}, '',
        ${sqlText(doc.signerParty ?? 'customer')}, 0, 0, ${sqlText(input['owner-admin-id'])},
        ${sqlText(approvedAt)}, ${sqlText(input['owner-admin-id'])}, ${sqlText(doc.familyKey || doc.id.toLowerCase())},
        '2026-11-22', 'owner_approved', NULL, ${sqlText(packetNotes)})
     ON CONFLICT(id) DO UPDATE SET
       title = excluded.title,
       category = excluded.category,
       version = excluded.version,
       content_text = excluded.content_text,
       content_sha256 = excluded.content_sha256,
       signer_party = excluded.signer_party,
       family_key = excluded.family_key,
       effective_date = excluded.effective_date,
       legal_review_status = excluded.legal_review_status,
       packet_notes = excluded.packet_notes,
       status = CASE WHEN document_templates.content_sha256 = excluded.content_sha256
                     THEN document_templates.status ELSE 'draft' END,
       updated_at = CURRENT_TIMESTAMP
     WHERE document_templates.content_sha256 = excluded.content_sha256;`,
    `INSERT OR IGNORE INTO admin_audit
       (id, actor_user_id, action, entity_type, entity_id, success, detail_json, created_at)
     VALUES (${sqlText(`audit_legal_import_tpl_${doc.id}`)}, ${sqlText(input['owner-admin-id'])},
       'documents.template_approved', 'document_template', ${sqlText(doc.id)}, 1,
       ${sqlJson({ source: 'owner-approved-library-2026-11-22', version: doc.version, contentSha256: doc.contentSha256 })},
       CURRENT_TIMESTAMP);`,
    '',
  );
}

for (const packet of staging.packets) {
  const bundleId = `bundle_${String(packet.code).replace(/[^a-z0-9]+/gi, '_')}`;
  lines.push(
    `INSERT INTO document_bundles
       (id, code, name, description, service_category, subject_type, status, version, purpose,
        packet_type, instructions, is_system, created_by_admin_user_id)
     VALUES
       (${sqlText(bundleId)}, ${sqlText(packet.code)}, ${sqlText(packet.name)}, ${sqlText(packet.instructions ?? '')},
        ${sqlText(packet.serviceCategory ?? 'general')}, ${sqlText(packet.subjectType)}, ${sqlText(packet.status)},
        1, ${sqlText(packet.purpose ?? 'customer')}, ${sqlText(packet.packetType ?? 'custom')},
        ${sqlText(packet.instructions ?? '')}, 0, ${sqlText(input['owner-admin-id'])})
     ON CONFLICT(id) DO UPDATE SET
       name = excluded.name,
       description = excluded.description,
       service_category = excluded.service_category,
       subject_type = excluded.subject_type,
       status = excluded.status,
       purpose = excluded.purpose,
       packet_type = excluded.packet_type,
       instructions = excluded.instructions,
       updated_at = CURRENT_TIMESTAMP;`,
    `DELETE FROM document_bundle_items WHERE bundle_id = ${sqlText(bundleId)};`,
  );
  packet.items.forEach((item, order) => {
    lines.push(
      `INSERT INTO document_bundle_items
         (bundle_id, template_id, sort_order, required, enforcement_stage, condition_key, condition_value, per_booking)
       VALUES (${sqlText(bundleId)}, ${sqlText(item.id)}, ${order}, ${Number(item.required) ? 1 : 0},
         ${sqlText(item.stage)}, ${sqlText(item.conditionKey ?? '')}, ${sqlText(item.conditionValue ?? '')},
         ${Number(item.perBooking) ? 1 : 0});`,
    );
  });
  lines.push(
    `INSERT OR IGNORE INTO admin_audit
       (id, actor_user_id, action, entity_type, entity_id, success, detail_json, created_at)
     VALUES (${sqlText(`audit_legal_import_pkt_${bundleId}`)}, ${sqlText(input['owner-admin-id'])},
       'documents.packet_imported', 'document_bundle', ${sqlText(bundleId)}, 1,
       ${sqlJson({ source: 'owner-approved-library-2026-11-22', code: packet.code, status: packet.status, items: packet.items.length })},
       CURRENT_TIMESTAMP);`,
    '',
  );
}

const outPath = path.resolve(input.out);
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, `${lines.join('\n')}\n`, { encoding: 'utf8' });
const report = {
  ok: true,
  generatedAt: approvedAt,
  staging: path.resolve(input.staging),
  manifest: path.resolve(input.manifest),
  sql: outPath,
  sqlSha256: crypto.createHash('sha256').update(fs.readFileSync(outPath)).digest('hex'),
  templates: documents.length,
  packets: staging.packets.map((packet) => ({
    code: packet.code,
    status: packet.status,
    documents: packet.items.length,
    required: packet.items.filter((item) => Number(item.required) === 1).length,
    perBooking: packet.items.filter((item) => Number(item.perBooking) === 1).length,
  })),
  activePackets: staging.packets.filter((packet) => packet.status === 'active').map((packet) => packet.code),
  unresolved: 0,
};
process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
