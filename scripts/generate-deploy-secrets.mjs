// Local deployment-secret workflow — Cloudflare Pages.
//
// Reads the local `.env` (git-ignored) and produces `deploy/secrets.env`
// (git-ignored) in the dotenv format accepted by:
//
//   npx wrangler pages secret bulk deploy/secrets.env --project-name sparkling-standard-cleaning
//
// It also prints which PUBLIC build-time variables must be entered in the
// Cloudflare dashboard, with values masked. It never prints secret values and
// never writes secrets anywhere except the git-ignored file.
//
// Usage: node scripts/generate-deploy-secrets.mjs

import fs from 'node:fs';
import path from 'node:path';

function loadDotEnv(file) {
  const values = {};
  if (!fs.existsSync(file)) return values;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (match) values[match[1]] = match[2].replace(/^["']|["']$/g, '');
  }
  return values;
}

/** Runtime secrets read by functions/api/*. */
const SECRET_KEYS = [
  'WEB3FORMS_ACCESS_KEY',
  'TURNSTILE_SECRET_KEY',
  'TRAVEL_ORIGIN',
  'ROUTES_API_KEY',
  'EIA_API_KEY',
];

/** Build-time public variables (inlined by Astro at build). */
const PUBLIC_KEYS = [
  'PUBLIC_SITE_URL',
  'PUBLIC_WEB3FORMS_ACCESS_KEY',
  'PUBLIC_UMAMI_WEBSITE_ID',
  'PUBLIC_GTM_CONTAINER_ID',
  'PUBLIC_TURNSTILE_SITE_KEY',
];

/** Non-secret runtime tuning values (dashboard "Text" variables, optional). */
const RUNTIME_TEXT_KEYS = ['ROUTES_PROVIDER', 'REFERENCE_GAS_PRICE', 'TRAVEL_CACHE_SECONDS'];

const env = { ...loadDotEnv('.env'), ...process.env };
const value = (key) => env[key]?.trim() ?? '';
const mask = (raw) => (raw ? `${raw.slice(0, 4)}…(${raw.length} chars)` : '(not set)');
const quote = (raw) => `"${raw.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;

const present = SECRET_KEYS.filter((key) => value(key));
const missingRequired = ['WEB3FORMS_ACCESS_KEY', 'TRAVEL_ORIGIN'].filter((key) => !value(key));

const outDir = path.join('deploy');
fs.mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, 'secrets.env');
const written = SECRET_KEYS.filter((key) => value(key));
fs.writeFileSync(
  outFile,
  '# Generated by scripts/generate-deploy-secrets.mjs — DO NOT COMMIT.\n' +
    '# Upload: npx wrangler pages secret bulk deploy/secrets.env --project-name sparkling-standard-cleaning\n' +
    written.map((key) => `${key}=${quote(value(key))}`).join('\n') +
    '\n',
  'utf8',
);

console.log(`✓ wrote ${outFile} with ${present.length}/${SECRET_KEYS.length} secret(s) set`);console.log('\nSecrets in the file (values hidden):');
for (const key of SECRET_KEYS) {
  console.log(`  ${key}: ${value(key) ? 'set' : 'MISSING'}`);
}

console.log('\nBuild-time PUBLIC variables for the Cloudflare dashboard (values masked):');
for (const key of PUBLIC_KEYS) {
  console.log(`  ${key}: ${mask(value(key))}`);
}

if (value('PUBLIC_WEB3FORMS_ACCESS_KEY') && value('WEB3FORMS_ACCESS_KEY')) {
  if (value('PUBLIC_WEB3FORMS_ACCESS_KEY') !== value('WEB3FORMS_ACCESS_KEY')) {
    console.warn(
      '\n! PUBLIC_WEB3FORMS_ACCESS_KEY and WEB3FORMS_ACCESS_KEY differ. They should be the same access key:\n' +
        '  the public one powers the static fallback, the server one powers /api/lead.',
    );
  }
}

console.log('\nOptional runtime text variables (dashboard, "Text" type):');
for (const key of RUNTIME_TEXT_KEYS) {
  console.log(`  ${key}: ${value(key) ? 'set' : '(default used)'}`);
}

console.log('\nNext steps:');
console.log('  1) npx wrangler login');
console.log('  2) npx wrangler pages secret bulk deploy/secrets.env --project-name sparkling-standard-cleaning');
console.log('  3) npx wrangler pages secret list --project-name sparkling-standard-cleaning');
console.log('  4) Enter the PUBLIC_* values (and PUBLIC_PREVIEW_MODE=true while staging) in the dashboard.');
console.log('  5) Trigger a new deployment so the Functions and build receive the updated bindings.');

if (missingRequired.length > 0) {
  console.error(`\n✗ Missing required value(s): ${missingRequired.join(', ')}`);
  console.error('  Fill them in .env (never committed) and rerun this script before deploying.');
  process.exit(1);
}

console.log('\n✓ required secret values present');
