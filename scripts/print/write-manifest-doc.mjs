// Writes the maintained field-acquisition manifest document from the canonical
// manifest module, so the documentation can never drift from the generator.
//
//   node scripts/print/write-manifest-doc.mjs
import fs from 'node:fs';
import path from 'node:path';
import { PIECES, VARIANTS, PRODUCTION_MIX, PRINT_GEOMETRY } from './manifest.mjs';
import { printQrMappings } from './qr-map.mjs';

const outPath = path.join('docs', 'marketing', 'field-acquisition', 'manifest.json');
const qrByAsset = new Map(printQrMappings().map((mapping) => [mapping.qrAssetId, mapping]));

const document = {
  note: 'Generated by scripts/print/write-manifest-doc.mjs from scripts/print/manifest.mjs — do not edit by hand.',
  geometry: PRINT_GEOMETRY,
  variants: VARIANTS,
  productionMix: PRODUCTION_MIX,
  pieces: PIECES.map((piece) => ({
    id: piece.id,
    name: piece.name,
    width: piece.width,
    height: piece.height,
    safeMargin: piece.safeMargin,
    qrMin: piece.qrMin,
    die: piece.die ?? null,
    stock: piece.stock,
    print: piece.print,
    firstRun: piece.firstRun,
    sides: piece.sides.map((side) => ({
      id: side.id,
      qr: side.qr
        ? {
            asset: side.qr,
            registryLinkId: qrByAsset.get(side.qr)?.linkId ?? null,
            url: qrByAsset.get(side.qr)?.url ?? null,
          }
        : null,
      captionMin: side.captionMin,
    })),
  })),
};

fs.writeFileSync(outPath, JSON.stringify(document, null, 2) + '\n', 'utf8');
console.log(`wrote ${outPath}`);
